import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pluginRequire = createRequire(
  path.join(root, "plugins/openclaw/package.json"),
);
const Ajv2020 = pluginRequire("ajv/dist/2020.js").default;
const addFormatsModule = pluginRequire("ajv-formats");
const addFormats = addFormatsModule.default ?? addFormatsModule;
const standaloneCode = pluginRequire("ajv/dist/standalone/index.js").default;
const { _ } = pluginRequire("ajv/dist/compile/codegen/index.js");
const check = process.argv.includes("--check");
const specs = [
  {
    name: "operator",
    input: "protocol/openapi/operator-v1.yaml",
    outputDir: "protocol/schema",
    schemas: {
      Decision: "decision.schema.json",
      Descriptor: "discovery.schema.json",
      ErrorEnvelope: "error.schema.json",
      BrokerEvent: "event.schema.json",
      RequestPage: "page.schema.json",
      Presentation: "presentation.schema.json",
      BrokerRequest: "request.schema.json",
    },
    idBase: "https://brokerkit.dev/schema/operator/v1/",
  },
  {
    name: "agent",
    input: "protocol/openapi/agent-v1.yaml",
    outputDir: "protocol/agent-schema",
    schemas: {
      Descriptor: "discovery.schema.json",
      ErrorEnvelope: "error.schema.json",
      Operation: "operation.schema.json",
      OperationPage: "page.schema.json",
      SubmitRequest: "submit.schema.json",
    },
    idBase: "https://brokerkit.io/schema/agent/v1/",
  },
  {
    name: "mcp",
    input: "protocol/openapi/mcp-v1.yaml",
    outputDir: "protocol/mcp-schema",
    schemas: {
      Grant: "grant.schema.json",
      Operation: "operation.schema.json",
      OperationPage: "page.schema.json",
      RequestIDConflict: "request-id-conflict.schema.json",
    },
    idBase: "https://brokerkit.io/schema/mcp/v1/",
  },
];

let stale = false;
const contractDigests = {};
for (const spec of specs) {
  const inputPath = path.join(root, spec.input);
  const source = readFileSync(inputPath, "utf8");
  const document = JSON.parse(source);
  const components = document.components?.schemas;
  if (!components || typeof components !== "object")
    throw new Error(`${spec.input} has no component schemas`);
  for (const [schemaName, filename] of Object.entries(spec.schemas)) {
    if (!components[schemaName])
      throw new Error(`${spec.input} has no ${schemaName} schema`);
    const artifact = {
      $comment: `Generated from ${spec.input}; do not edit.`,
      $schema: "https://json-schema.org/draft/2020-12/schema",
      $id: spec.idBase + filename,
      ...rewriteRefs(structuredClone(components[schemaName])),
      $defs: definitionsFor(components[schemaName], components),
    };
    emit(
      path.join(root, spec.outputDir, filename),
      `${JSON.stringify(artifact, null, 2)}\n`,
    );
  }
  contractDigests[spec.name] = contractDigest(document, spec, components);
  if (spec.name === "operator") {
    await emitOperatorWrapper(contractDigests.operator, components);
    emitOperatorValidators(components);
  }
}
emitContractDigests(contractDigests);
if (stale) process.exit(1);

function contractDigest(document, spec, components) {
  const schemas = {};
  for (const [schemaName, filename] of Object.entries(spec.schemas)) {
    schemas[filename] = {
      $schema: "https://json-schema.org/draft/2020-12/schema",
      $id: spec.idBase + filename,
      ...rewriteRefs(structuredClone(components[schemaName])),
      $defs: definitionsFor(components[schemaName], components),
    };
  }
  const canonical = canonicalize({ openapi: document, schemas });
  return `sha256:${createHash("sha256").update(JSON.stringify(canonical)).digest("hex")}`;
}

function canonicalize(value) {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(
    Object.keys(value)
      .sort()
      .map((key) => [key, canonicalize(value[key])]),
  );
}

function emitContractDigests(digests) {
  const generated = `// Code generated by protocol/generate-artifacts.mjs. DO NOT EDIT.\n\npackage contract\n\nconst (\n\tOperatorV1Digest = ${JSON.stringify(digests.operator)}\n\tAgentV1Digest    = ${JSON.stringify(digests.agent)}\n)\n`;
  emit(path.join(root, "protocol/contract/generated.go"), generated);
}

function rewriteRefs(value) {
  if (Array.isArray(value)) return value.map(rewriteRefs);
  if (!value || typeof value !== "object") return value;
  for (const [key, child] of Object.entries(value)) {
    if (key === "$ref" && typeof child === "string") {
      value[key] = child.replace("#/components/schemas/", "#/$defs/");
    } else {
      value[key] = rewriteRefs(child);
    }
  }
  return value;
}

async function emitOperatorWrapper(contractDigest, schemas) {
  const request = schemas.BrokerRequest;
  const presentation = schemas.Presentation;
  const event = schemas.BrokerEvent;
  const error = schemas.Error;
  const decision = schemas.Decision;
  const page = schemas.RequestPage;
  const generated = `// Generated from protocol/openapi/operator-v1.yaml. Do not edit.
import type { components } from "./openapi-operator-v1.js";

export const OPERATOR_V1_SCHEMA_SHA256 = ${JSON.stringify(contractDigest)};
export const operatorV1 = ${JSON.stringify(
    {
      apiVersion: schemas.Descriptor.properties.api_version.const,
      statuses: schemas.Status.enum,
      actions: schemas.Action.enum,
      risks: presentation.properties.risk.enum,
      eventKinds: event.properties.kind.enum,
      errorCodes: error.properties.code.enum,
      limits: {
        id: request.properties.id.maxLength,
        requester: request.properties.requester.maxLength,
        operation: request.properties.operation.maxLength,
        reason: request.properties.request_reason.maxLength,
        actor: request.properties.decided_by.maxLength,
        title: presentation.properties.title.maxLength,
        summary: presentation.properties.summary.maxLength,
        facts: presentation.properties.facts.maxItems,
        factLabel: schemas.Fact.properties.label.maxLength,
        factValue: schemas.Fact.properties.value.maxLength,
        cursor: event.properties.cursor.maxLength,
        page: page.properties.requests.maxItems,
        idempotencyKey: decision.properties.idempotency_key.maxLength,
        errorMessage: error.properties.message.maxLength,
        correlationId: error.properties.correlation_id.maxLength,
      },
    },
    null,
    2,
  )} as const;

export type Decision = components["schemas"]["Decision"];
export type Discovery = components["schemas"]["Descriptor"];
export type ErrorEnvelope = components["schemas"]["ErrorEnvelope"];
export type BrokerEvent = components["schemas"]["BrokerEvent"];
export type RequestPage = components["schemas"]["RequestPage"];
export type Presentation = components["schemas"]["Presentation"];
export type BrokerRequest = components["schemas"]["BrokerRequest"];
export type UISnapshot = components["schemas"]["UISnapshot"];
export type UISnapshotEvent = components["schemas"]["UISnapshotEvent"];
export type UISummary = components["schemas"]["UISummary"];
`;
  emit(
    path.join(root, "plugins/openclaw/src/generated/operator-v1.ts"),
    await format(generated, { parser: "typescript" }),
  );
}

function emitOperatorValidators(components) {
  const names = [
    "Descriptor",
    "Health",
    "BrokerRequest",
    "RequestPage",
    "BrokerEvent",
    "ErrorEnvelope",
    "UISnapshot",
    "UISnapshotEvent",
    "UISummary",
    "UIRequest",
  ];
  const rootID = "https://brokerkit.dev/schema/operator/v1/runtime/components";
  const definitions = Object.fromEntries(
    Object.entries(components).map(([name, schema]) => [
      name,
      rewriteRefs(structuredClone(schema)),
    ]),
  );
  const ajv = new Ajv2020({
    strict: true,
    allErrors: false,
    code: { source: true, esm: true, formats: _`formats` },
  });
  addFormats(ajv);
  ajv.addSchema({
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: rootID,
    $defs: definitions,
  });
  for (const name of names) {
    ajv.addSchema(
      {
        $schema: "https://json-schema.org/draft/2020-12/schema",
        $id: `https://brokerkit.dev/schema/operator/v1/runtime/${name}`,
        $ref: `${rootID}#/$defs/${name}`,
      },
      name,
    );
  }
  const exports = Object.fromEntries(
    names.map((name) => [`validate${name}`, name]),
  );
  const generated = standaloneCode(ajv, exports)
    .replace(
      /const (func\d+) = require\("ajv\/dist\/runtime\/equal"\)\.default;/gu,
      "const $1 = equal;",
    )
    .replace(
      /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/gu,
      "const $1 = ucs2length;",
    );
  if (/\brequire\s*\(|\bnew Function\s*\(|\beval\s*\(/u.test(generated)) {
    throw new Error(
      "generated operator validators contain runtime code loading",
    );
  }
  emit(
    path.join(root, "plugins/openclaw/src/generated/operator-validators.ts"),
    `/* eslint-disable */\n// @ts-nocheck -- generated Ajv standalone code\n// Generated from protocol/openapi/operator-v1.yaml. Do not edit.\nimport formatsModule from "ajv-formats/dist/formats.js";\nimport equalModule from "ajv/dist/runtime/equal.js";\nimport ucs2lengthModule from "ajv/dist/runtime/ucs2length.js";\nconst formats = formatsModule.fullFormats;\nconst equal = equalModule.default ?? equalModule;\nconst ucs2length = ucs2lengthModule.default ?? ucs2lengthModule;\n${generated}\n`,
  );
}

function definitionsFor(schema, components) {
  const names = new Set();
  collectComponentRefs(schema, names);
  const definitions = {};
  while (names.size > Object.keys(definitions).length) {
    for (const name of [...names].sort()) {
      if (definitions[name]) continue;
      const definition = components[name];
      if (!definition) throw new Error(`unknown component schema ${name}`);
      collectComponentRefs(definition, names);
      definitions[name] = rewriteRefs(structuredClone(definition));
    }
  }
  return definitions;
}

function collectComponentRefs(value, names) {
  if (Array.isArray(value)) {
    for (const child of value) collectComponentRefs(child, names);
    return;
  }
  if (!value || typeof value !== "object") return;
  for (const [key, child] of Object.entries(value)) {
    if (
      key === "$ref" &&
      typeof child === "string" &&
      child.startsWith("#/components/schemas/")
    ) {
      names.add(child.slice("#/components/schemas/".length));
    } else {
      collectComponentRefs(child, names);
    }
  }
}

function emit(filename, contents) {
  if (check) {
    let current = "";
    try {
      current = readFileSync(filename, "utf8");
    } catch {}
    if (current !== contents) {
      process.stderr.write(`${path.relative(root, filename)} is stale\n`);
      stale = true;
    }
    return;
  }
  mkdirSync(path.dirname(filename), { recursive: true });
  writeFileSync(filename, contents);
}
