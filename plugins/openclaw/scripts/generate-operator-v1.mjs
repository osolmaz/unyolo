import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const packageDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const schemaDir = path.resolve(packageDir, "..", "..", "protocol", "schema");
const outputPath = path.join(packageDir, "src", "generated", "operator-v1.ts");
const names = {
  "decision.schema.json": "Decision",
  "discovery.schema.json": "Discovery",
  "error.schema.json": "ErrorEnvelope",
  "event.schema.json": "BrokerEvent",
  "page.schema.json": "RequestPage",
  "presentation.schema.json": "Presentation",
  "request.schema.json": "BrokerRequest",
};
const files = readdirSync(schemaDir)
  .filter((file) => file.endsWith(".schema.json"))
  .sort();
const source = new Map(
  files.map((file) => [
    file,
    {
      text: readFileSync(path.join(schemaDir, file), "utf8"),
      schema: undefined,
    },
  ]),
);
for (const value of source.values()) value.schema = JSON.parse(value.text);
const digest = createHash("sha256");
for (const [file, value] of source)
  digest.update(file).update("\0").update(value.text);

const request = source.get("request.schema.json").schema;
const event = source.get("event.schema.json").schema;
const presentation = source.get("presentation.schema.json").schema;
const decision = source.get("decision.schema.json").schema;
const page = source.get("page.schema.json").schema;
const errorEnvelope = source.get("error.schema.json").schema;
const error = errorEnvelope.properties.error;

const generated =
  `// Generated by scripts/generate-operator-v1.mjs. Do not edit.\n\n` +
  `export const OPERATOR_V1_SCHEMA_SHA256 = ${JSON.stringify(digest.digest("hex"))};\n\n` +
  `export const operatorV1 = ${JSON.stringify(
    {
      apiVersion: source.get("discovery.schema.json").schema.properties
        .api_version.const,
      statuses: request.properties.status.enum,
      actions: request.properties.allowed_actions.items.enum,
      risks: presentation.properties.risk.enum,
      eventKinds: event.properties.kind.enum,
      errorCodes: error.properties.code.enum,
      limits: {
        id: request.properties.id.maxLength,
        requester: request.properties.requester.maxLength,
        operation: request.properties.operation.maxLength,
        reason: request.properties.request_reason.maxLength,
        actor: request.properties.decided_by.maxLength,
        title: presentation.properties.title.maxLength,
        summary: presentation.properties.summary.maxLength,
        facts: presentation.properties.facts.maxItems,
        factLabel:
          presentation.properties.facts.items.properties.label.maxLength,
        factValue:
          presentation.properties.facts.items.properties.value.maxLength,
        cursor: event.properties.cursor.maxLength,
        page: page.properties.requests.maxItems,
        idempotencyKey: decision.properties.idempotency_key.maxLength,
        errorMessage: error.properties.message.maxLength,
        correlationId: error.properties.correlation_id.maxLength,
      },
    },
    null,
    2,
  )} as const;\n\n` +
  files
    .map(
      (file) =>
        `export type ${names[file]} = ${typeFor(source.get(file).schema)};`,
    )
    .join("\n\n") +
  "\n";
const output = await format(generated, { parser: "typescript" });

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outputPath, "utf8");
  } catch {
    // A missing generated file is reported by the comparison below.
  }
  if (current !== output) {
    process.stderr.write(
      "Operator V1 TypeScript bindings are stale; run pnpm generate.\n",
    );
    process.exit(1);
  }
} else {
  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, output);
}

function typeFor(schema) {
  if (schema.$ref) return names[path.basename(schema.$ref)];
  if (Object.hasOwn(schema, "const")) return JSON.stringify(schema.const);
  if (schema.enum)
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (Array.isArray(schema.type)) {
    return schema.type.map((type) => typeFor({ ...schema, type })).join(" | ");
  }
  if (schema.type === "object") {
    const required = new Set(schema.required ?? []);
    const properties = Object.entries(schema.properties ?? {}).map(
      ([name, value]) =>
        `${JSON.stringify(name)}${required.has(name) ? "" : "?"}: ${typeFor(value)};`,
    );
    return `{ ${properties.join(" ")} }`;
  }
  if (schema.type === "array") return `Array<${typeFor(schema.items)}> `;
  if (schema.type === "integer" || schema.type === "number") return "number";
  if (schema.type === "boolean") return "boolean";
  if (schema.type === "null") return "null";
  return "string";
}
